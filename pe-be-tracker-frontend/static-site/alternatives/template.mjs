import { readFileSync } from "node:fs";

const SITE = "https://www.personalbestie.com";
const APP = "https://app.personalbestie.com";
const AUTHOR = { name: "Nicolas Leyton", url: `${APP}/about/` };

const styles = readFileSync(new URL("./styles.css", import.meta.url), "utf8");

export const esc = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

const jsonLdScript = (graph) =>
  JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 4)
    .replaceAll("<", "\\u003c")
    .split("\n")
    .map((line) => `    ${line}`)
    .join("\n");

const cta = (campaign, classes, label) =>
  `<a href="${APP}?utm_source=alternatives&amp;utm_medium=cta&amp;utm_campaign=${campaign}" class="${classes}">${esc(label)}</a>`;

const cell = ({ kind = "plain", text }) => {
  const safe = esc(text);
  if (kind === "check") return `<td><span class="badge-check">✓ ${safe}</span></td>`;
  if (kind === "cross") return `<td><span class="badge-cross">✕ ${safe}</span></td>`;
  if (kind === "neutral") return `<td><span class="badge-neutral">${safe}</span></td>`;
  if (kind === "highlight") return `<td class="font-black text-[var(--primary-rose)]">${safe}</td>`;
  return `<td>${safe}</td>`;
};

