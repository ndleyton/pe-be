const breadcrumb = (current, { link = true } = {}) => `            <!-- Breadcrumbs -->
            <nav class="mb-6 flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-[color:var(--muted-foreground)]">
                <a href="${SITE}/" class="hover:text-[var(--primary-rose)] transition-colors">Home</a>
                <span>/</span>
                ${
                  link
                    ? `<a href="${SITE}/alternatives/" class="hover:text-[var(--primary-rose)] transition-colors">Alternatives</a>`
                    : `<span class="text-[var(--foreground)]">Alternatives</span>`
                }${
                  current
                    ? `
                <span>/</span>
                <span class="text-[var(--foreground)]">${esc(current)}</span>`
                    : ""
                }
            </nav>`;

const sourcesNote = ({ name, verified, sources }) => {
  const links = sources
    .map((source) =>
      source.url
        ? `<a href="${esc(source.url)}" rel="noopener" class="underline hover:text-[var(--primary-rose)]">${esc(source.label)}</a>`
        : esc(source.label),
    )
    .join(", ");
  return `            <!-- Sources -->
            <section class="my-8">
                <p class="text-xs leading-relaxed text-[color:var(--muted-foreground)]">
                    ${esc(name)} pricing and plan limits last verified on <time datetime="${verified}">${verified}</time> against: ${links}. Other feature details reflect publicly available information. Apps change often; if something here is out of date, <a href="mailto:ndleyton@uc.cl" class="underline hover:text-[var(--primary-rose)]">let us know</a>.
                </p>
            </section>`;
};

